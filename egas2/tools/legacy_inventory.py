#!/usr/bin/env python3
"""Write egas2/memory/LEGACY_INVENTORY.md and seed egas2/memory/MIGRATION_MAP.csv (one row per legacy file).
Legacy = every .sysml/.kerml outside egas2/. Safe to re-run: existing CSV rows are kept."""
import re, csv, json, hashlib, sys, collections
from sysml_scan import repo_root, sysml_files, clean, top_level, read, EGAS2

root = repo_root(); egas2 = EGAS2
KINDS = ["part def", "item def", "action def", "requirement def", "state def", "constraint def", "calc def",
         "verification def", "use case def", "port def", "attribute def", "enum def", "metadata def",
         "concern def", "viewpoint def", "view def"]
files = sysml_files(root, skip_under=egas2)
rows, pk, imps_by_pkg = [], {}, {}
for f in files:
    raw = read(f).replace("\r", "")
    lines = raw.split("\n")
    commented = sum(1 for l in lines if l.lstrip().startswith("//"))
    c = clean(raw)
    tl = top_level(c)
    pkgs = [n for k, n, _ in tl if k == "package"]
    for n in pkgs:
        pk[n] = f
        imps_by_pkg[n] = set(re.findall(r"import\s+(?:all\s+)?'?(\w+)'?\s*::", c))
    kinds = {k: len(re.findall(r"\b" + k + r"\b", c)) for k in KINDS}
    rows.append((f.relative_to(root).as_posix(), len(lines), commented, pkgs, kinds,
                 len(re.findall(r"\bsatisfy\b", c)), len(re.findall(r"\bverify\b", c))))

graph = {p: {t for t in imps_by_pkg[p] if t in pk and t != p} for p in pk}
idx, low, st, on, sccs, n = {}, {}, [], set(), [], [0]
def sc(v):
    idx[v] = low[v] = n[0]; n[0] += 1; st.append(v); on.add(v)
    for w in graph[v]:
        if w not in idx: sc(w); low[v] = min(low[v], low[w])
        elif w in on: low[v] = min(low[v], idx[w])
    if low[v] == idx[v]:
        comp = []
        while True:
            w = st.pop(); on.discard(w); comp.append(w)
            if w == v: break
        sccs.append(comp)
for v in list(pk):
    if v not in idx: sc(v)

out = ["# LEGACY_INVENTORY (generated by tools/legacy_inventory.py)", "",
       "| file | lines | commented | top-level packages | satisfy | verify | defs |", "|---|---|---|---|---|---|---|"]
for path, total, com, pkgs, kinds, sat, ver in rows:
    d = ", ".join(f"{k.split()[0]}:{v}" for k, v in kinds.items() if v)
    out.append(f"| {path} | {total} | {com} | {', '.join(pkgs)} | {sat} | {ver} | {d} |")
out += ["", f"files: {len(rows)}, total lines: {sum(r[1] for r in rows)}, commented lines: {sum(r[2] for r in rows)}", "",
        "## Import cycles between legacy packages"]
out += [f"- {sorted(c)}" for c in sccs if len(c) > 1] or ["- none"]
mem = egas2 / "memory"; mem.mkdir(parents=True, exist_ok=True)
(mem / "LEGACY_INVENTORY.md").write_text("\n".join(out) + "\n", encoding="utf-8")

csv_path = mem / "MIGRATION_MAP.csv"
header = ["legacy_file", "legacy_element", "kind", "disposition", "target", "task", "note"]
existing = []
if csv_path.exists():
    existing = list(csv.reader(csv_path.open(encoding="utf-8", newline="")))[1:]
have = {(r[0], r[1]) for r in existing if r}
for path, *_ in rows:
    if (path, "*") not in have:
        existing.append([path, "*", "file", "unmapped", "", "", ""])
with csv_path.open("w", newline="", encoding="utf-8") as fh:
    w = csv.writer(fh, lineterminator="\n"); w.writerow(header); w.writerows(existing)
hp = mem / "LEGACY_HASHES.json"
if not hp.exists() or "--rebaseline" in sys.argv:   # immutable baseline of legacy files
    hp.write_text(json.dumps({f.relative_to(root).as_posix(): hashlib.sha1(f.read_bytes()).hexdigest() for f in files},
                             indent=0), encoding="utf-8")
unm = sum(1 for r in existing if r and r[3] == "unmapped")
print(f"legacy files: {len(rows)}; MIGRATION_MAP rows: {len(existing)}; unmapped: {unm}")
